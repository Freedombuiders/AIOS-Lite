#!/usr/bin/env node
// Manifest-driven copier: GỐC (fork) -> AIOS-Lite. Refuses any file that exists in upstream/main.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const TARGET_ROOT = path.resolve(HERE, '..', '..');
// the private source repo the port came from; set AIOS_PORT_SOURCE or keep it next to this repo
const DEFAULT_SOURCE = process.env.AIOS_PORT_SOURCE || path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'claudeclaw-os');

export function existsUpstream(source, rel, ref = 'upstream/main') {
  return spawnSync('git', ['-C', source, 'cat-file', '-e', `${ref}:${rel}`], { stdio: 'ignore' }).status === 0;
}

function walk(abs, rel, out) {
  const st = fs.statSync(abs);
  if (st.isDirectory()) {
    for (const n of fs.readdirSync(abs).sort()) walk(path.join(abs, n), `${rel}/${n}`, out);
  } else if (st.isFile()) out.push(rel);
}

const norm = (p) => p.replace(/\\/g, '/').replace(/\/+$/, '');
const isDropped = (rel, drops) => drops.some((d) => rel === d || rel.startsWith(d + '/'));

/** Plan + (unless dryRun) execute. Returns {copied, bytes, refused, skipped, dropped, existing, rows}. */
export function runManifest(manifest, { source, targetRoot = TARGET_ROOT, dryRun = false, force = false, ref = 'upstream/main' }) {
  const drops = (manifest.drop ?? []).map((d) => norm(d.from));
  const plan = [];
  const res = { copied: 0, bytes: 0, refused: [], dropped: [], existing: [], missing: [], rows: [] };
  for (const e of manifest.entries ?? []) {
    const from = norm(e.from), to = norm(e.to);
    const abs = path.join(source, from);
    if (!fs.existsSync(abs)) { res.missing.push(from); continue; }
    const files = [];
    walk(abs, from, files);
    const isDir = fs.statSync(abs).isDirectory();
    for (const f of files) {
      if (isDropped(f, drops)) { res.dropped.push(f); continue; }
      const dest = isDir ? `${to}/${f.slice(from.length + 1)}` : to;
      if (existsUpstream(source, f, ref)) { res.refused.push(f); continue; }
      plan.push({ f, dest, kind: e.kind ?? '', note: e.note ?? '' });
    }
  }
  if (res.refused.length || res.missing.length) return res; // nothing written
  for (const p of plan) {
    const d = path.join(targetRoot, p.dest);
    if (fs.existsSync(d) && !force) { res.existing.push(p.dest); continue; }
    const size = fs.statSync(path.join(source, p.f)).size;
    if (!dryRun) {
      fs.mkdirSync(path.dirname(d), { recursive: true });
      fs.copyFileSync(path.join(source, p.f), d);
    }
    res.copied++; res.bytes += size; res.rows.push(p);
  }
  return res;
}

export function appendLog(manifest, res, { targetRoot = TARGET_ROOT, source }) {
  const mod = manifest.module;
  // Manifests that land in core (integrations, teams…) log to docs/dev/port, not a fake modules/<id> folder.
  const isModule = manifest.entries.some((e) => (e.to ?? '').startsWith(`modules/${mod}/`));
  const dir = isModule ? path.join(targetRoot, 'modules', mod) : path.join(targetRoot, 'docs', 'dev', 'port');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, isModule ? 'PORTING.md' : `${mod}.PORTING.md`);
  let out = '';
  if (!fs.existsSync(file)) out += `# Porting log: ${mod}\n\nGenerated by scripts/port/copy.mjs. Source: GỐC (fork-only files, none exist in upstream/main).\n\n`;
  out += `\n## Run ${new Date().toISOString()}\n\n| from | to | kind | note |\n|---|---|---|---|\n`;
  for (const r of res.rows) out += `| ${r.f} | ${r.dest} | ${r.kind} | ${String(r.note).replace(/\|/g, '\\|')} |\n`;
  if (manifest.drop?.length) {
    out += `\n### Dropped\n\n`;
    for (const d of manifest.drop) out += `- \`${d.from}\`: ${d.reason ?? ''}\n`;
  }
  fs.appendFileSync(file, out);
}

function main() {
  const args = process.argv.slice(2);
  const flag = (n) => args.includes(n);
  const si = args.indexOf('--source');
  const source = path.resolve(si >= 0 ? args[si + 1] : process.env.AIOS_PORT_SOURCE || DEFAULT_SOURCE);
  const mf = args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--source');
  if (!mf) { console.error('usage: copy.mjs <manifest.json> [--dry-run] [--force] [--source <path>]'); process.exit(2); }
  const manifest = JSON.parse(fs.readFileSync(mf, 'utf8'));
  const dryRun = flag('--dry-run');
  const res = runManifest(manifest, { source, dryRun, force: flag('--force') });
  if (res.missing.length) console.error(`ERROR missing in source: ${res.missing.join(', ')}`);
  if (res.refused.length) {
    console.error(`ERROR refused (exists in upstream/main, license): \n  ${res.refused.join('\n  ')}\nNothing written.`);
  }
  if (res.refused.length || res.missing.length) process.exit(1);
  if (!dryRun) appendLog(manifest, res, { source });
  console.log(`${dryRun ? '[dry-run] ' : ''}module=${manifest.module} copied=${res.copied} bytes=${res.bytes} refused=0 dropped=${res.dropped.length} existing-skipped=${res.existing.length}`);
  if (res.existing.length) console.log(`existing (use --force): ${res.existing.join(', ')}`);
  if (dryRun) for (const r of res.rows) console.log(`  ${r.f} -> ${r.dest}`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
